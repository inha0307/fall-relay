-- Fall-Relay bridge schema, PostgreSQL baseline (v1.0.0).
-- Column types match the reference deployment: bigint, double precision (Unix seconds), text.
-- Later changes go in NNNN_<name>.sql and are applied with postgres/upgrade.py.

CREATE TABLE cameras (
    id               text PRIMARY KEY,
    label            text NOT NULL,
    location         text NOT NULL DEFAULT '',
    enabled          bigint NOT NULL DEFAULT 1,
    sort_order       bigint NOT NULL DEFAULT 0,
    token_hash       text,
    token_created_at double precision,
    created_at       double precision NOT NULL,
    updated_at       double precision NOT NULL
);

CREATE TABLE events (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id         text NOT NULL,
    track_id          bigint,
    started_at        double precision NOT NULL,
    ended_at          double precision,
    max_score         double precision NOT NULL,
    fall_slots        bigint NOT NULL DEFAULT 1,
    review_status     text NOT NULL DEFAULT 'new',
    note              text NOT NULL DEFAULT '',
    reviewed_at       double precision,
    reviewed_by       text,
    model_run_id      text,
    event_uid         text,
    source            text NOT NULL DEFAULT 'inferred_v1' CHECK (source IN ('inferred_v1','edge_event')),
    run_id            text,
    edge_state        text CHECK (edge_state IN ('IDLE','SUSPECT','ALERT','POST_FALL','COOLDOWN')),
    onset_sensor_ns   bigint,
    decided_sensor_ns bigint,
    decided_at        double precision,
    clock_offset_s    double precision,
    clock_rtt_s       double precision,
    received_at       double precision,
    close_reason      text CHECK (close_reason IN ('recovered','timeout','track_lost','runtime_stop')),
    last_message_seq  bigint,
    last_received_at  double precision,
    clock_usable      bigint NOT NULL DEFAULT 0 CHECK (clock_usable IN (0,1)),
    late_arrival      bigint NOT NULL DEFAULT 0 CHECK (late_arrival IN (0,1))
);
CREATE INDEX idx_events_started ON events(started_at);
CREATE INDEX idx_events_camera ON events(camera_id, started_at);
CREATE UNIQUE INDEX ux_events_uid ON events(event_uid) WHERE event_uid IS NOT NULL;

CREATE TABLE metrics (
    ts              double precision NOT NULL,
    camera_id       text NOT NULL,
    video_connected bigint NOT NULL,
    edge_connected  bigint NOT NULL,
    video_fps       double precision,
    edge_hz         double precision,
    latency_p50_ms  double precision,
    latency_p95_ms  double precision,
    results         bigint NOT NULL DEFAULT 0,
    ineligible      bigint NOT NULL DEFAULT 0
);
CREATE INDEX idx_metrics_cam_ts ON metrics(camera_id, ts);

CREATE TABLE edge_protocol_runs (
    camera_id     text NOT NULL REFERENCES cameras(id),
    run_id        text NOT NULL,
    protocol      text NOT NULL CHECK (protocol IN ('inferred_v1','edge_event')),
    first_seen_at double precision NOT NULL,
    PRIMARY KEY (camera_id, run_id)
);

CREATE TABLE push_subscriptions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_code       text NOT NULL,
    device_id       text NOT NULL UNIQUE,
    endpoint        text NOT NULL UNIQUE,
    p256dh          text NOT NULL,
    auth            text NOT NULL,
    user_agent      text NOT NULL DEFAULT '',
    created_at      double precision NOT NULL,
    last_success_at double precision,
    revoked_at      double precision
);
CREATE INDEX ix_push_user ON push_subscriptions(user_code) WHERE revoked_at IS NULL;

CREATE TABLE alerts (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           bigint REFERENCES events(id),
    type               text NOT NULL CHECK (type IN ('fall','camera_offline','device_warning')),
    camera_id          text NOT NULL REFERENCES cameras(id),
    state              text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','sent','delivered','acknowledged','resolved','expired')),
    escalation_level   bigint NOT NULL DEFAULT 0 CHECK (escalation_level >= 0),
    created_at         double precision NOT NULL,
    first_sent_at      double precision,
    first_delivered_at double precision,
    acknowledged_at    double precision,
    acknowledged_by    text,
    resolved_at        double precision,
    resolved_by        text,
    resolution         text CHECK (resolution IN ('fall','fa_sitting','fa_lying','fa_bending','fa_other','uncertain','recovered','device_other')),
    note               text NOT NULL DEFAULT '',
    notification_mode  text NOT NULL DEFAULT 'live' CHECK (notification_mode IN ('live','manual_review')),
    suppression_reason text,
    CHECK (type <> 'fall' OR event_id IS NOT NULL),
    CHECK (type = 'fall' OR resolution IS NULL OR resolution IN ('recovered','device_other','uncertain')),
    CHECK (type <> 'fall' OR resolution IS NULL OR resolution NOT IN ('recovered','device_other')),
    CHECK ((notification_mode = 'live' AND suppression_reason IS NULL)
        OR (notification_mode = 'manual_review' AND suppression_reason IS NOT NULL
            AND suppression_reason IN ('event_too_old','clock_unreliable')))
);
CREATE UNIQUE INDEX ux_alerts_fall_event ON alerts(event_id) WHERE type = 'fall';
CREATE UNIQUE INDEX ux_alerts_open_device ON alerts(camera_id, type)
    WHERE type IN ('camera_offline','device_warning') AND state NOT IN ('resolved','expired');
CREATE INDEX ix_alerts_state_time ON alerts(state, created_at);
CREATE INDEX ix_alerts_camera_time ON alerts(camera_id, created_at);

CREATE TABLE alert_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id   bigint NOT NULL REFERENCES alerts(id),
    at         double precision NOT NULL,
    actor      text,
    action     text NOT NULL CHECK (action IN ('created','sent','delivered','acknowledged','resolved','escalated','expired','send_failed')),
    from_state text,
    to_state   text,
    detail     text NOT NULL DEFAULT '{}'
);
CREATE INDEX ix_alert_log_alert ON alert_log(alert_id, id);

CREATE TABLE edge_event_receipts (
    event_uid       text NOT NULL,
    message_seq     bigint NOT NULL CHECK (message_seq >= 1),
    kind            text NOT NULL CHECK (kind IN ('open','update','close')),
    semantic_sha256 text NOT NULL CHECK (length(semantic_sha256) = 64),
    event_id        bigint NOT NULL REFERENCES events(id),
    alert_id        bigint NOT NULL REFERENCES alerts(id),
    received_at     double precision NOT NULL,
    payload         text,
    PRIMARY KEY (event_uid, message_seq)
);

CREATE TABLE alert_deliveries (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id         bigint NOT NULL REFERENCES alerts(id),
    escalation_level bigint NOT NULL CHECK (escalation_level >= 0),
    channel          text NOT NULL CHECK (channel IN ('webpush','sse')),
    recipient        text,
    device_id        text,
    subscription_id  bigint REFERENCES push_subscriptions(id),
    attempted_at     double precision NOT NULL,
    result           text NOT NULL CHECK (result IN ('sent','failed','revoked','broadcast')),
    http_status      bigint,
    error            text,
    delivered_at     double precision,
    client_at        double precision
);
CREATE INDEX ix_deliveries_alert ON alert_deliveries(alert_id);

CREATE TABLE alert_receipts (
    delivery_id bigint NOT NULL REFERENCES alert_deliveries(id),
    device_id   text NOT NULL,
    actor       text NOT NULL,
    received_at double precision NOT NULL,
    client_at   double precision,
    PRIMARY KEY (delivery_id, device_id)
);

CREATE TABLE alert_dispatch_jobs (
    job_key          text PRIMARY KEY,
    alert_id         bigint NOT NULL REFERENCES alerts(id),
    escalation_level bigint NOT NULL CHECK (escalation_level >= 0),
    channel          text NOT NULL CHECK (channel IN ('webpush','sse')),
    recipient        text,
    subscription_id  bigint REFERENCES push_subscriptions(id),
    state            text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','processing','retry','done','failed','cancelled')),
    attempts         bigint NOT NULL DEFAULT 0,
    next_attempt_at  double precision NOT NULL,
    leased_until     double precision,
    last_error       text,
    created_at       double precision NOT NULL
);
CREATE INDEX ix_dispatch_due ON alert_dispatch_jobs(state, next_attempt_at);

CREATE TABLE alert_settings (
    key        text PRIMARY KEY,
    value      text NOT NULL,
    updated_at double precision NOT NULL,
    updated_by text
);

CREATE TABLE edge_clip_jobs (
    event_id   bigint PRIMARY KEY REFERENCES events(id),
    camera_id  text NOT NULL REFERENCES cameras(id),
    trigger_at double precision NOT NULL,
    state      text NOT NULL CHECK (state IN ('queued','claimed','started','unavailable')),
    error      text,
    created_at double precision NOT NULL
);

CREATE TABLE device_commands (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id    text NOT NULL,
    camera_id    text NOT NULL,
    command      text NOT NULL CHECK (command IN ('restart_inference','stop_inference','start_inference','logs','reboot','decision_log_start','decision_log_stop','decision_log_collect')),
    requested_by text NOT NULL,
    requested_at double precision NOT NULL,
    state        text NOT NULL CHECK (state IN ('queued','sent','done','failed','expired')),
    sent_at      double precision,
    finished_at  double precision,
    result       text,
    params_json  text NOT NULL DEFAULT '{}'
);
CREATE INDEX device_commands_by_device ON device_commands(device_id, id);
CREATE UNIQUE INDEX ux_device_commands_active ON device_commands(device_id) WHERE state IN ('queued','sent');

CREATE TABLE ingress_traffic (
    ts         double precision NOT NULL,
    camera_id  text NOT NULL,
    kind       text NOT NULL CHECK (kind IN ('result','event','clip','health','command','context','video','diagnostics')),
    requests   bigint NOT NULL,
    bytes      bigint NOT NULL,
    interval_s double precision NOT NULL
);
CREATE INDEX ingress_traffic_by_camera ON ingress_traffic(camera_id, ts);

CREATE TABLE decision_log_archives (
    session_id    text PRIMARY KEY,
    device_id     text NOT NULL,
    camera_id     text NOT NULL,
    sha256        text NOT NULL,
    size          bigint NOT NULL,
    records       bigint NOT NULL,
    started_at    double precision NOT NULL,
    ended_at      double precision NOT NULL,
    received_at   double precision NOT NULL,
    state         text NOT NULL CHECK (state IN ('ready','expired')),
    manifest_json text NOT NULL
);
CREATE INDEX decision_logs_device ON decision_log_archives(device_id, received_at);

CREATE TABLE decision_log_audit (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text NOT NULL,
    actor      text NOT NULL,
    action     text NOT NULL,
    at         double precision NOT NULL
);

CREATE TABLE model_runs (
    run_id        text PRIMARY KEY,
    camera_id     text NOT NULL,
    bundle_id     text NOT NULL,
    bundle_sha256 text NOT NULL,
    config_sha256 text NOT NULL,
    first_seen    double precision NOT NULL,
    last_seen     double precision NOT NULL,
    identity_json text NOT NULL
);

CREATE TABLE hardware_devices (
    device_id   text PRIMARY KEY,
    camera_id   text NOT NULL,
    received_at double precision NOT NULL,
    payload     text NOT NULL
);

CREATE TABLE hardware_samples (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id   text NOT NULL,
    received_at double precision NOT NULL,
    payload     text NOT NULL
);
CREATE INDEX hardware_sample_time ON hardware_samples(device_id, received_at);
