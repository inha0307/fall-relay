/*
 * Fall-Relay web application store (PostgreSQL, schema FALLRELAY_APP_SCHEMA, default "app"). Server code only —
 * never import from the browser.
 *
 * Tables:
 *   accounts               responder/viewer/administrator accounts; user_code (U-0001 …) is the permanent identifier
 *   sessions               login sessions (hashed tokens)
 *   login_logs             every sign-in attempt
 *   account_audit          who changed which account and how (kept even after an account is deleted)
 *   counters               monotonic counters (user codes are never reissued)
 *   account_camera_grants  cameras a responder may read
 *   app_schema_migrations  ledger of the schema scripts applied here
 * Fall events, cameras and clips live in the bridge's schema of the same database (video_bridge.py).
 *
 * Statements use ? placeholders, converted to $n. A Db offers get/all/run/exec and transaction(fn) on one client.
 */
import { createHash, randomUUID } from 'node:crypto';
import pg from 'pg';
import { poolConfig } from './pgConn.mjs';

pg.types.setTypeParser(20, Number); // bigint columns hold seconds and counters, never beyond 2^53

export const SCHEMA_VERSION = 1;
export const ROLES = ['admin', 'viewer', 'responder'];
export const ACCOUNT_STATUSES = ['active', 'deactivated'];
export const LOGIN_ID_PATTERN = /^[A-Za-z0-9._@+-]{2,100}$/;

export const SCHEMA = `
CREATE TABLE accounts (
    id                   text PRIMARY KEY,
    user_code            text NOT NULL UNIQUE,
    login_id             text NOT NULL,
    name                 text NOT NULL DEFAULT '',
    email                text NOT NULL DEFAULT '',
    affiliation          text NOT NULL DEFAULT '',
    role                 text NOT NULL DEFAULT 'viewer' CHECK (role IN ('admin', 'viewer', 'responder')),
    status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'deactivated')),
    must_change_password integer NOT NULL DEFAULT 0,
    password_hash        text,
    created_at           text NOT NULL,
    updated_at           text NOT NULL,
    last_login_at        text,
    deactivated_at       text,
    deactivated_by       text,
    deactivation_reason  text NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX accounts_login_id_idx ON accounts (lower(login_id));
CREATE TABLE sessions (
    token_hash text PRIMARY KEY,
    account_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at bigint NOT NULL,
    expires_at bigint NOT NULL,
    ip         text,
    user_agent text
);
CREATE INDEX sessions_account_idx ON sessions (account_id);
CREATE TABLE login_logs (
    id            text PRIMARY KEY,
    account_id    text REFERENCES accounts(id) ON DELETE SET NULL,
    login_user_id text,
    ip_address    text,
    status        text NOT NULL DEFAULT 'success',
    created_at    text NOT NULL
);
CREATE INDEX login_logs_created_idx ON login_logs (created_at DESC);
CREATE INDEX login_logs_user_idx ON login_logs (lower(login_user_id), created_at);
CREATE TABLE account_audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          text NOT NULL,
    actor_id    text,
    actor_code  text,
    target_id   text,
    target_code text NOT NULL,
    action      text NOT NULL,
    details     text NOT NULL DEFAULT '{}'
);
CREATE INDEX account_audit_target_idx ON account_audit (target_id, at);
CREATE TABLE counters (
    name  text PRIMARY KEY,
    value bigint NOT NULL
);
CREATE TABLE account_camera_grants (
    account_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    camera_id  text NOT NULL,
    granted_at text NOT NULL,
    granted_by text NOT NULL,
    PRIMARY KEY (account_id, camera_id)
);
`;
const LEDGER =
    'CREATE TABLE IF NOT EXISTS app_schema_migrations (version bigint PRIMARY KEY, checksum text NOT NULL, applied_at text NOT NULL)';
export const SCHEMA_CHECKSUM = createHash('sha256').update(SCHEMA).digest('hex');

/* ? placeholders → $1, $2 …, leaving quoted literals and identifiers alone. */
export function placeholders(sql) {
    let out = '',
        quote = null,
        n = 0;
    for (let i = 0; i < sql.length; i++) {
        const char = sql[i];
        if (quote) {
            out += char;
            if (char === quote) {
                if (sql[i + 1] === quote) out += sql[++i];
                else quote = null;
            }
        } else if (char === "'" || char === '"') {
            quote = char;
            out += char;
        } else out += char === '?' ? '$' + ++n : char;
    }
    return out;
}

class Executor {
    constructor(client) {
        this.client = client;
    }
    async query(sql, params = []) {
        return this.client.query(placeholders(sql), params);
    }
    async get(sql, ...params) {
        return (await this.query(sql, params)).rows[0] ?? null;
    }
    async all(sql, ...params) {
        return (await this.query(sql, params)).rows;
    }
    /* { changes, lastId } — lastId when the statement RETURNING id. */
    async run(sql, ...params) {
        const result = await this.query(sql, params);
        return { changes: result.rowCount ?? 0, lastId: result.rows[0]?.id ?? null };
    }
    async exec(sql) {
        await this.client.query(sql);
    }
}

export class Db extends Executor {
    constructor(pool, schema) {
        super(pool);
        this.pool = pool;
        this.schema = schema;
    }
    /* fn(tx) runs on one client inside BEGIN … COMMIT; any throw rolls back. */
    async transaction(fn) {
        const client = await this.pool.connect();
        try {
            await client.query('BEGIN');
            const result = await fn(new Executor(client));
            await client.query('COMMIT');
            return result;
        } catch (error) {
            await client.query('ROLLBACK').catch(() => {});
            throw error;
        } finally {
            client.release();
        }
    }
    async close() {
        await this.pool.end();
    }
}

async function initialize(db) {
    await db.transaction(async tx => {
        await tx.exec(`CREATE SCHEMA IF NOT EXISTS ${db.schema}`);
        await tx.exec(LEDGER);
        const applied = await tx.all('SELECT version, checksum FROM app_schema_migrations ORDER BY version');
        if (applied.length === 0) {
            await tx.exec(SCHEMA);
            await tx.run('INSERT INTO app_schema_migrations VALUES (?,?,?)', SCHEMA_VERSION, SCHEMA_CHECKSUM, nowIso());
            return;
        }
        if (applied[0].version !== SCHEMA_VERSION || applied[0].checksum !== SCHEMA_CHECKSUM)
            throw new Error('Account schema checksum mismatch; the database was initialised by other software');
        if (applied.length > 1) throw new Error('Account database is newer than this software');
    });
}

/* Open the store: the schema is created and initialised when empty, verified otherwise. */
export async function openDb(connectionString = process.env.FALLRELAY_DATABASE_URL, schema = undefined) {
    const config = poolConfig(connectionString, schema);
    const { schema: name, ...settings } = config;
    const db = new Db(new pg.Pool(settings), name);
    try {
        await initialize(db);
        return db;
    } catch (error) {
        await db.close().catch(() => {});
        throw error;
    }
}

/* One pool per Next.js server process (survives dev-mode module reloads). */
export function getDb() {
    globalThis.__fallRelayAppDb ??= openDb();
    return globalThis.__fallRelayAppDb;
}

export const nowIso = () => new Date().toISOString();
export const newId = () => randomUUID();

const formatUserCode = n => `U-${String(n).padStart(4, '0')}`;

/* Next user code (U-0001, U-0002, …). Call inside the transaction that inserts the account. */
export async function nextUserCode(tx) {
    const row = await tx.get(
        "INSERT INTO counters(name, value) VALUES ('user_code', 1) ON CONFLICT(name) DO UPDATE SET value = counters.value + 1 RETURNING value"
    );
    return formatUserCode(row.value);
}

/* Record an account change. actor/target: { id, user_code }; details must not contain secrets. */
export async function audit(tx, actor, target, action, details = {}) {
    await tx.run(
        `INSERT INTO account_audit(at, actor_id, actor_code, target_id, target_code, action, details)
                VALUES (?, ?, ?, ?, ?, ?, ?)`,
        nowIso(),
        actor?.id ?? null,
        actor?.user_code ?? null,
        target.id,
        target.user_code,
        action,
        JSON.stringify(details)
    );
}

export function publicAccount(row) {
    if (!row) return null;
    const { password_hash, ...rest } = row; // never expose the hash
    return { ...rest, must_change_password: !!row.must_change_password, has_password: password_hash != null };
}

/* Sign-in accepts the login id or the account's e-mail (both case-insensitive). */
export async function findAccountForLogin(db, userid) {
    const value = String(userid || '').trim();
    if (!value) return null;
    return db.get(
        "SELECT * FROM accounts WHERE lower(login_id) = lower(?) OR (email <> '' AND lower(email) = lower(?))",
        value,
        value
    );
}
